import assert from 'node:assert/strict'
import fs from 'node:fs'

const funcionUrl = new URL('../supabase/functions/limpiar-datos-prueba/index.ts', import.meta.url)
const permisosUrl = new URL('../supabase/fix-limpieza-datos-prueba.sql', import.meta.url)
assert.equal(fs.existsSync(funcionUrl), true, 'Debe existir la función de limpieza de desarrollo')
assert.equal(fs.existsSync(permisosUrl), true, 'Debe existir el SQL de permisos de limpieza')
const funcion = fs.readFileSync(funcionUrl, 'utf8')
const permisos = fs.readFileSync(permisosUrl, 'utf8')
const config = fs.readFileSync(new URL('../supabase/config.toml', import.meta.url), 'utf8')
const supabaseData = fs.readFileSync(new URL('./supabaseData.ts', import.meta.url), 'utf8')
const adminApp = fs.readFileSync(new URL('./AdminApp.tsx', import.meta.url), 'utf8')
const cabecera = fs.readFileSync(new URL('./components/admin/AdminCabecera.tsx', import.meta.url), 'utf8')

assert.match(funcion, /SUPABASE_SERVICE_ROLE_KEY/)
assert.match(funcion, /comprobantes-pago/)
assert.match(funcion, /\.list\(/)
assert.doesNotMatch(funcion, /storage\.objects/)
assert.match(funcion, /storage\.from\(BUCKET\)/)
assert.match(funcion, /pago_comprobantes/)
assert.match(funcion, /pagos_reserva/)
assert.match(funcion, /reservas/)
assert.match(funcion, /clientes/)
assert.match(funcion, /bloqueos_eventos/)
assert.match(funcion, /numeros_bloqueados/)
assert.match(funcion, /numeros_confiables/)
assert.match(funcion, /reserva_rate_limits/)
assert.doesNotMatch(funcion, /horarios_bloqueados/)
assert.match(permisos, /grant usage on schema public, storage to service_role/i)
assert.match(permisos, /grant select, delete[\s\S]+public\.pago_comprobantes[\s\S]+to service_role/i)
assert.match(permisos, /grant select, delete on table storage\.objects to service_role/i)

assert.match(config, /\[functions\.limpiar-datos-prueba\]/)
assert.match(config, /verify_jwt = true/)
assert.match(supabaseData, /limpiarDatosPruebaRemoto/)
assert.match(supabaseData, /functions\.invoke\('limpiar-datos-prueba'/)
assert.doesNotMatch(supabaseData, /service_role/i)
assert.match(adminApp, /limpiarDatosPruebaRemoto/)
assert.match(adminApp, /limpiandoDatosPrueba/)
assert.match(cabecera, /limpiandoDatosPrueba/)
assert.match(cabecera, /import\.meta\.env\.DEV/)
assert.match(cabecera, /Limpiar datos de prueba/)

console.log('✔ limpiezaDatosPrueba.check.ts OK')
