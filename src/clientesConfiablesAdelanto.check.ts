import assert from 'node:assert/strict'
import fs from 'node:fs'

const migration = fs.readFileSync(new URL('../supabase/fix-clientes-confiables-adelanto.sql', import.meta.url), 'utf8')
const schema = fs.readFileSync(new URL('../supabase/schema.sql', import.meta.url), 'utf8')
const permissions = fs.readFileSync(new URL('../supabase/permissions.sql', import.meta.url), 'utf8')
const supabaseData = fs.readFileSync(new URL('./supabaseData.ts', import.meta.url), 'utf8')
const app = fs.readFileSync(new URL('./App.tsx', import.meta.url), 'utf8')
const almacen = fs.readFileSync(new URL('./almacen.ts', import.meta.url), 'utf8')
const edgeFunction = fs.readFileSync(new URL('../supabase/functions/registrar-adelanto-yape/index.ts', import.meta.url), 'utf8')
const datosReserva = fs.readFileSync(new URL('./components/cliente/DatosReserva.tsx', import.meta.url), 'utf8')
const reservaCompletada = fs.readFileSync(new URL('./components/cliente/ReservaCompletada.tsx', import.meta.url), 'utf8')
const misReservas = fs.readFileSync(new URL('./components/cliente/MisReservas.tsx', import.meta.url), 'utf8')
const adminCard = fs.readFileSync(new URL('./components/admin/AdminReservaCard.tsx', import.meta.url), 'utf8')
const estilos = fs.readFileSync(new URL('./index.css', import.meta.url), 'utf8')

assert.match(migration, /create or replace function public\.es_numero_confiable_publico\(p_celular text\)/)
assert.match(migration, /returns boolean[\s\S]*?security definer[\s\S]*?set search_path = public, pg_temp/)
assert.match(migration, /create(?: or replace)? function public\.crear_reserva_publica\([\s\S]*?p_sin_adelanto boolean/)
assert.match(migration, /pago_estado text[\s\S]*?token text/)
assert.match(migration, /v_numero_confiable boolean/)
assert.match(migration, /p_sin_adelanto and not v_numero_confiable[\s\S]*?numero_no_confiable/)
assert.match(migration, /numeros_bloqueados[\s\S]*?celular_bloqueado/)
assert.match(migration, /v_pago_estado := case[\s\S]*?else 'pendiente'/)
assert.match(migration, /v_pago_requerido := case[\s\S]*?else 10/)
assert.match(migration, /now\(\) \+ interval '30 minutes'/)
assert.match(migration, /v_pago_estado := case[\s\S]*?then 'no_requerido'/)
assert.match(migration, /drop function if exists public\.crear_reserva_publica\(integer, date, numeric, numeric, text, text\)/)
assert.match(migration, /revoke all on function public\.es_numero_confiable_publico\(text\)/)
assert.doesNotMatch(migration, /grant .* on table public\.numeros_confiables .*anon/)

for (const source of [schema, permissions]) {
  assert.match(source, /es_numero_confiable_publico/)
  assert.match(source, /p_sin_adelanto boolean/)
  assert.match(source, /pago_estado text/)
}

assert.match(supabaseData, /export async function verificarNumeroConfiableRemoto\(celular: string\): Promise<boolean>/)
assert.match(supabaseData, /rpc\('es_numero_confiable_publico'/)
assert.match(supabaseData, /p_sin_adelanto: sinAdelanto/)
assert.match(supabaseData, /numero_no_confiable/)
assert.match(app, /verificarNumeroConfiableRemoto/)
assert.match(app, /reserve: reservarCliente/)
assert.match(almacen, /leerNumerosConfiables\(\)/)
assert.match(edgeFunction, /pago_estado === 'no_requerido'[\s\S]*?reserva_no_autorizada/)
assert.match(datosReserva, /checkTrustedNumber/)
assert.match(datosReserva, /sinAdelanto/)
assert.doesNotMatch(datosReserva, /className="reserva-sin-adelanto"/)
assert.match(datosReserva, /Confirmar reserva/)
assert.match(datosReserva, /Selecciona tu comprobante/)
assert.match(reservaCompletada, /Reserva confirmada\. No requiere adelanto\./)
assert.match(reservaCompletada, /Reserva asegurada\. Tu comprobante está pendiente de revisión\./)
assert.match(misReservas, /r\.pagoEstado === 'no_requerido'[\s\S]*?Reserva confirmada/)
assert.match(adminCard, /sinAdelanto \? 'Finalizar reserva' : 'Finalizar y confirmar pago'/)
assert.match(estilos, /reserva-sin-adelanto/)

console.log('OK: contrato de clientes confiables y adelanto')
